# PlatformIO pre-build script: gzip the web page (src/index_html.h raw string) into src/index_html_gz.h.
# ~21 kB of HTML/JS → ~6 kB on the wire: faster over the ESP's AP and far less TCP buffer pressure on the ESP's heap.
# Runs inside PlatformIO's Python on every build (stdlib only). Only rewrites the output when the page changed.
import gzip, os, re
Import("env")  # noqa: F821  (PlatformIO SCons environment)

src = os.path.join(env["PROJECT_DIR"], "src", "index_html.h")
dst = os.path.join(env["PROJECT_DIR"], "src", "index_html_gz.h")

html = open(src, encoding="utf-8").read()
m = re.search(r'R"SUNHTML\((.*)\)SUNHTML"', html, re.S)
if not m:
    raise SystemExit("gen_html_gz.py: raw string R\"SUNHTML(...)SUNHTML\" not found in src/index_html.h")
page = m.group(1).encode("utf-8")
gz = gzip.compress(page, compresslevel=9, mtime=0)

body = ",".join(str(b) for b in gz)
out = ("// index_html_gz.h — GENERATED by tools/gen_html_gz.py from src/index_html.h on every build. Do not edit.\n"
       "#pragma once\n#include <pgmspace.h>\n"
       f"#define INDEX_HTML_GZ_LEN {len(gz)}\n#define INDEX_HTML_RAW_LEN {len(page)}\n"
       f"static const uint8_t INDEX_HTML_GZ[] PROGMEM = {{{body}}};\n")
if not os.path.exists(dst) or open(dst, encoding="utf-8").read() != out:
    open(dst, "w", encoding="utf-8").write(out)
    print(f"gen_html_gz.py: page {len(page)} B → {len(gz)} B gzip")
